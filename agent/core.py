def plain(text: str) -> str:
    """Убрать markdown-разметку из ответа модели — общий для CLI и Telegram."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text or "")
    text = re.sub(r"(?m)^\s*#{1,6}\s*", "", text)
    return text.replace("`", "")
